"""Build the offline HTML from docs/tools/ten-viewer. Standard library only.

The readable JS/CSS/HTML in that directory is the only maintained source.
The generated standalone.html embeds those same modules and the parser worker.
"""
import base64
import json
import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/tools/ten-viewer'
IMPORT = re.compile(r"(^[ \t]*(?:import|export)\b[^;]*?\bfrom\s*)(['\"])([^'\"]+)\2", re.MULTILINE)


def build():
    modules = {}

    def module(name):
        if name in modules:
            return
        modules[name] = ''
        text = (SOURCE / name).read_text(encoding='utf-8')

        def replace(match):
            prefix, quote, target = match.groups()
            target = ('vendor/three.module.js' if target == 'three'
                      else posixpath.normpath(posixpath.join(posixpath.dirname(name), target)))
            if not (SOURCE / target).is_file():
                raise ValueError(f'Unresolved module: {name}: {target}')
            module(target)
            return prefix + quote + 'ten-viewer/' + target + quote

        modules[name] = IMPORT.sub(replace, text)

    module('app.js')
    # Bundle the worker's pure-data module graph in dependency order. No browser
    # imports or second parser implementation are maintained for offline use.
    worker_parts = []
    worker_seen = set()

    def worker_module(name):
        if name in worker_seen:
            return
        worker_seen.add(name)
        text = (SOURCE / name).read_text(encoding='utf-8')

        def dependency(match):
            target = posixpath.normpath(posixpath.join(posixpath.dirname(name), match.group(3)))
            worker_module(target)
            return ''

        text = re.sub(IMPORT.pattern + r'\s*;', dependency, text, flags=re.MULTILINE)
        text = re.sub(r'\bexport (?=(?:class|function|const)\b)', '', text)
        worker_parts.append(text)

    worker_module('level-worker.js')
    worker = '\n'.join(worker_parts)
    encoded = {name: base64.b64encode(code.encode()).decode() for name, code in modules.items()}
    payload = json.dumps({'modules': encoded, 'worker': worker}, ensure_ascii=True).replace('<', '\\u003c')
    bootstrap = '''<script>
// Generated by tools/build_ten_viewer.py. Edit the source modules, not this file.
const embedded=PAYLOAD;
const imports={};
for(const [name,base64] of Object.entries(embedded.modules)){
  const bytes=Uint8Array.from(atob(base64),c=>c.charCodeAt(0));
  imports['ten-viewer/'+name]=URL.createObjectURL(new Blob([bytes],{type:'text/javascript'}));
}
window.TEN_VIEWER_CONFIG={workerSource:embedded.worker};
const map=document.createElement('script');map.type='importmap';map.textContent=JSON.stringify({imports});document.head.append(map);
const main=document.createElement('script');main.type='module';main.textContent="import 'ten-viewer/app.js';";document.body.append(main);
</script>'''.replace('PAYLOAD', payload)
    html = (SOURCE / 'index.html').read_text(encoding='utf-8')
    html = re.sub(r'  <script type="importmap">.*?</script>\n', '', html)
    html = html.replace('<link rel="stylesheet" href="style.css">', '<style>' + (SOURCE / 'style.css').read_text(encoding='utf-8') + '</style>')
    html = re.sub(r'<a id="offlineDownload".*?</a>', '', html)
    html = html.replace('<script type="module" src="app.js"></script>', bootstrap)
    license_text = (SOURCE / 'vendor/THREE-LICENSE.txt').read_text(encoding='utf-8')
    html = html.replace('</body>', '<!--\n' + license_text + '\n-->\n</body>')
    output = SOURCE / 'standalone.html'
    output.write_text(html, encoding='utf-8')
    print(f'Built {output.relative_to(ROOT)} ({output.stat().st_size:,} bytes; {len(modules)} embedded modules).')
    return output


if __name__ == '__main__':
    build()
